//! `.inp` deck writer — the inverse of `solvix_io`'s parser for the
//! keywords `abaqus2solvix` produces: `*NODE`, `*ELEMENT`, `*NSET`,
//! `*ELSET`, `*MATERIAL`/`*ELASTIC`/`*DENSITY`, `*SOLID SECTION`,
//! `*STEP`, `*STATIC`, `*DYNAMIC`, `*BOUNDARY`, `*CLOAD`, `*DLOAD`
//! (element P-faces and GRAV).

use solvix_core::{ElemKind, Model};

/// Render `model` as an Abaqus keyword deck. Steps are written with
/// `OP=NEW` and their full accumulated BC/load state, which re-parses
/// to the same Model (the parser stores each step's accumulated state).
pub fn write_deck(model: &Model) -> String {
    let mut d = String::new();
    d.push_str("** Generated by abaqus2solvix (Solvix) — translated Abaqus script.\n");
    if model.mesh.nodes.is_empty() {
        d.push_str("** empty model (nothing translatable found)\n");
        return d;
    }
    d.push_str("*HEADING\n    abaqus2solvix translation\n");

    d.push_str("*NODE\n");
    for n in &model.mesh.nodes {
        d.push_str(&format!("{}, {}, {}\n", n.id, n.coords[0], n.coords[1]));
    }

    if !model.mesh.elements.is_empty() {
        d.push_str(&format!(
            "*ELEMENT, TYPE={}, ELSET=ALL\n",
            kind_name(model.mesh.elements[0].kind)
        ));
        for e in &model.mesh.elements {
            let conn: Vec<String> = e.connectivity.iter().map(|c| c.to_string()).collect();
            d.push_str(&format!("{}, {}\n", e.id, conn.join(", ")));
        }
        for set in &model.elsets {
            d.push_str(&format!("*ELSET, ELSET={}\n", set.name));
            for chunk in set.element_ids.chunks(8) {
                let ids: Vec<String> = chunk.iter().map(|i| i.to_string()).collect();
                d.push_str(&format!("{}\n", ids.join(", ")));
            }
        }
    }

    for (i, m) in model.materials.iter().enumerate() {
        d.push_str(&format!("*MATERIAL, NAME={}\n", m.name));
        d.push_str("*ELASTIC\n");
        d.push_str(&format!("{}, {}\n", m.youngs_modulus, m.poisson_ratio));
        if i == 0 {
            // One model-wide density (v1), parked under the first material.
            d.push_str("*DENSITY\n");
            d.push_str(&format!("{}\n", model.density));
        }
    }

    if !model.mat_assignments.is_empty() {
        for (elset, mat) in &model.mat_assignments {
            d.push_str(&format!("*SOLID SECTION, ELSET={elset}, MATERIAL={mat}\n"));
            d.push_str(&format!("{}\n", model.thickness));
        }
    } else if !model.materials.is_empty() && !model.mesh.elements.is_empty() {
        d.push_str(&format!(
            "*SOLID SECTION, ELSET=ALL, MATERIAL={}\n{}\n",
            model.materials[0].name, model.thickness
        ));
    }

    let mut nset_no = 0usize;
    if model.steps.is_empty() {
        write_bc_loads(
            &mut d,
            &model.boundary_conditions,
            &model.cloads,
            &[],
            None,
            &mut nset_no,
        );
    } else {
        for step in &model.steps {
            d.push_str(&format!("*STEP, NAME={}, OP=NEW\n", step.name));
            match &step.dynamics {
                Some(dy) => {
                    d.push_str("*DYNAMIC\n");
                    d.push_str(&format!("{}, {}\n", dy.dt, dy.duration));
                }
                None => d.push_str("*STATIC\n"),
            }
            write_bc_loads(
                &mut d,
                &step.boundary_conditions,
                &step.cloads,
                &step.dloads,
                step.gravity,
                &mut nset_no,
            );
            d.push_str("*END STEP\n");
        }
    }
    d
}

fn write_bc_loads(
    d: &mut String,
    bcs: &[solvix_core::BoundaryCondition],
    cloads: &[solvix_core::ConcentratedLoad],
    dloads: &[solvix_core::DistributedLoad],
    gravity: Option<(f64, [f64; 3])>,
    nset_no: &mut usize,
) {
    let mut bc_lines = Vec::new();
    for bc in bcs {
        if bc.node_ids.is_empty() || bc.dofs.is_empty() {
            continue;
        }
        let target = if bc.node_ids.len() == 1 {
            bc.node_ids[0].to_string()
        } else {
            *nset_no += 1;
            let name = format!("NSET{nset_no}");
            d.push_str(&format!("*NSET, NSET={name}\n"));
            for chunk in bc.node_ids.chunks(8) {
                let ids: Vec<String> = chunk.iter().map(|i| i.to_string()).collect();
                d.push_str(&format!("{}\n", ids.join(", ")));
            }
            name
        };
        for (a, b) in dof_ranges(&bc.dofs) {
            if a == b {
                bc_lines.push(format!("{target}, {a}\n"));
            } else {
                bc_lines.push(format!("{target}, {a}, {b}\n"));
            }
        }
    }
    if !bc_lines.is_empty() {
        d.push_str("*BOUNDARY\n");
        for l in bc_lines {
            d.push_str(&l);
        }
    }

    if !cloads.is_empty() {
        d.push_str("*CLOAD\n");
        for cl in cloads {
            d.push_str(&format!("{}, {}, {}\n", cl.node_id, cl.dof, cl.value));
        }
    }

    if !dloads.is_empty() {
        d.push_str("*DLOAD\n");
        for dl in dloads {
            d.push_str(&format!(
                "{}, P{}, {}\n",
                dl.element_id, dl.face, dl.magnitude
            ));
        }
    }
    if let Some((g, dir)) = gravity {
        d.push_str("*DLOAD\n");
        d.push_str(&format!("GRAV, {g}, {}, {}, {}\n", dir[0], dir[1], dir[2]));
    }
}

/// Compress a dof list into inclusive (first, last) ranges.
fn dof_ranges(dofs: &[usize]) -> Vec<(usize, usize)> {
    let mut v = dofs.to_vec();
    v.sort_unstable();
    v.dedup();
    let mut out = Vec::new();
    for &df in &v {
        match out.last_mut() {
            Some((_, b)) if *b + 1 == df => *b = df,
            _ => out.push((df, df)),
        }
    }
    out
}

fn kind_name(k: ElemKind) -> &'static str {
    match k {
        ElemKind::Cps3 => "CPS3",
        ElemKind::Cps4 => "CPS4",
        ElemKind::Cps8 => "CPS8",
        ElemKind::Cpe4 => "CPE4",
        ElemKind::Cpe8 => "CPE8",
        ElemKind::C3d8 => "C3D8",
        ElemKind::C3d4 => "C3D4",
        ElemKind::B31 => "B31",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use solvix_core::{BoundaryCondition, ConcentratedLoad, Material};
    use solvix_io::parse_inp;

    fn tiny_model() -> Model {
        Model {
            mesh: solvix_core::Mesh {
                nodes: vec![
                    solvix_core::Node {
                        id: 1,
                        coords: [0.0, 0.0, 0.0],
                    },
                    solvix_core::Node {
                        id: 2,
                        coords: [1.0, 0.0, 0.0],
                    },
                    solvix_core::Node {
                        id: 3,
                        coords: [1.0, 1.0, 0.0],
                    },
                    solvix_core::Node {
                        id: 4,
                        coords: [0.0, 1.0, 0.0],
                    },
                ],
                elements: vec![solvix_core::Element {
                    id: 1,
                    kind: ElemKind::Cps4,
                    connectivity: vec![1, 2, 3, 4],
                }],
            },
            thickness: 0.5,
            density: 2700.0,
            materials: vec![Material {
                name: "ALU".into(),
                youngs_modulus: 70e9,
                poisson_ratio: 0.33,
            }],
            elsets: vec![solvix_core::ElementSet {
                name: "ALL".into(),
                element_ids: vec![1],
            }],
            mat_assignments: vec![("ALL".into(), "ALU".into())],
            steps: vec![solvix_core::Step {
                name: "Step-1".into(),
                boundary_conditions: vec![BoundaryCondition {
                    node_ids: vec![1, 4],
                    dofs: vec![1, 2],
                }],
                cloads: vec![ConcentratedLoad {
                    node_id: 2,
                    dof: 1,
                    value: 100.0,
                }],
                dloads: vec![solvix_core::DistributedLoad {
                    element_id: 1,
                    face: 2,
                    magnitude: 1e6,
                }],
                gravity: Some((9.81, [0.0, -1.0, 0.0])),
                ..Default::default()
            }],
            ..Default::default()
        }
    }

    #[test]
    fn round_trips_through_parse_inp() {
        let deck = write_deck(&tiny_model());
        let (m, report) = parse_inp(&deck).unwrap();
        assert!(report.warnings.is_empty(), "{:?}", report.warnings);
        assert_eq!(m.mesh.nodes.len(), 4);
        assert_eq!(m.mesh.elements.len(), 1);
        assert_eq!(m.thickness, 0.5);
        assert_eq!(m.density, 2700.0);
        assert_eq!(m.materials[0].name, "ALU");
        assert_eq!(m.steps.len(), 1);
        let s = &m.steps[0];
        assert_eq!(s.name, "Step-1");
        assert_eq!(s.boundary_conditions.len(), 1);
        assert_eq!(s.boundary_conditions[0].node_ids, vec![1, 4]);
        assert_eq!(s.boundary_conditions[0].dofs, vec![1, 2]);
        assert_eq!(s.cloads.len(), 1);
        assert_eq!(s.cloads[0].value, 100.0);
        assert_eq!(s.dloads.len(), 1);
        assert_eq!(s.dloads[0].face, 2);
        assert_eq!(s.gravity.unwrap().0, 9.81);
    }
}
